/** SOS_PIN：SOS 按钮接入的 GPIO 引脚（使用内部上拉，无需外接电阻） */
#define SOS_PIN  25

/**
 * SOS_HOLD_MS：长按多少毫秒才触发 SOS（防止误触）
 * 默认 2000ms（2 秒），可根据需要调整。
 */
#define SOS_HOLD_MS  2000

/**
 * SOS_DEBOUNCE_MS：按钮消抖时间（毫秒）
 * 机械按钮按下瞬间触点会弹跳，需要等信号稳定后再确认。
 * 50ms 是常用经验值，太小容易误触，太大会感觉迟钝。
 */
#define SOS_DEBOUNCE_MS  50
