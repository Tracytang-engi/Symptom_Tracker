// ═══════════════════════════════════════════════════
//  硬件引脚定义
// ═══════════════════════════════════════════════════

/**
 * FSR_PIN：FSR406 力敏电阻的信号输出引脚
 *
 * 硬件接线（必读）：
 *   - FSR406 一端 → 3.3V
 *   - FSR406 另一端 → GPIO34  ← 接这里
 *   - GPIO34 同时通过一个 10kΩ 电阻下拉到 GND
 *
 * 为什么用 GPIO34？
 *   ESP32 的 GPIO34~39 是"仅输入"引脚（Input-Only），
 *   没有内部上下拉电阻，专为 ADC 设计，噪声更小。
 *   GPIO34 = ADC1 通道 6，使用 ADC1 不会与 WiFi/BLE 冲突。
 */
#define FSR_PIN  34

/**
 * MOTOR_PIN：输出控制引脚（当前用 LED 代替振动马达测试）
 *
 * ── 当前接线（LED + 限流电阻，测试用）──────────────────
 *   GPIO27 → 440Ω 电阻 → LED 阳极（长脚 +）
 *                          LED 阴极（短脚 −） → GND
 *
 *   电流估算：(3.3V − 2.0V) / 440Ω ≈ 3mA
 *   ESP32 GPIO 最大可输出 ~12mA，3mA 完全安全，无需三极管。
 *   LED 亮 = 马达震动，LED 灭 = 马达停止。
 *
 * ── 正式马达接线（备用，等有三极管后替换）──────────────
 *   GPIO27 → 1kΩ 电阻 → S8050 基极（B）
 *   S8050 集电极（C） → 马达负极
 *   马达正极 → 3.3V
 *   S8050 发射极（E） → GND
 *   马达两端并联 1N4148 续流二极管（防反电动势烧毁引脚）
 *
 *   切换方式：只需换接线，代码无需任何修改。
 */
#define MOTOR_PIN  27

// ═══════════════════════════════════════════════════
//  FSR 采样参数
// ═══════════════════════════════════════════════════

/**
 * FSR_THRESHOLD：判断"有按压"的 ADC 阈值（触发事件检测用）
 *
 * ESP32 ADC 分辨率为 12 位，范围 0~4095。
 * 未按压时电路接近 0；按压越重，值越大。
 *
 * 200 / 4095 ≈ 5%，相当于较轻的触碰即可触发。
 * 如果误触发太多，可以适当调高（例如 400~600）。
 */
#define FSR_THRESHOLD  200

/**
 * FSR_MAP_MAX：压力映射的 ADC 上限（LED/马达强度用）
 *
 * 这个值代表"认为是最大力度"的 ADC 值，
 * 超过它后 LED/马达就维持在 PWM_MAX 不再增加。
 *
 * 调参方法：
 *   1. 打开 Serial Monitor，用你认为的"最大力度"按压 FSR
 *   2. 观察输出的 Pxxxx 值
 *   3. 把那个值填在这里
 *
 * 例如：中等力度到 4095 → 把 FSR_MAP_MAX 改成 2000，
 *       这样中等力度就对应 50% 亮度，重按才全亮。
 *
 * 注意：FSR_MAP_MAX 必须大于 FSR_THRESHOLD。
 */
#define FSR_MAP_MAX  1500

/**
 * FSR_DEBOUNCE_COUNT：软件消抖连续采样次数
 *
 * 连续读到 N 次超过阈值，才确认"按下"；
 * 连续读到 N 次低于阈值，才确认"松开"。
 * 防止信号抖动造成误触发。
 */
#define FSR_DEBOUNCE_COUNT  3

/**
 * FSR_SAMPLE_INTERVAL_MS：主循环采样间隔（毫秒）
 *
 * 20ms = 50Hz 采样率，对于手动按压事件已经足够精细。
 * 改小可以提高时间分辨率，但会增加处理器负载。
 */
#define FSR_SAMPLE_INTERVAL_MS  20

// ═══════════════════════════════════════════════════
//  事件记录参数
// ═══════════════════════════════════════════════════

/**
 * MAX_SAMPLES：单次按压事件最多保存的采样点数
 *
 * 20ms × 500 = 10000ms = 最多记录 10 秒的压力曲线。
 * 每个点占 2 字节（uint16_t），共 1000 字节。
 * ESP32 有 520KB RAM，完全够用。
 *
 * 如果按压超过 10 秒，超出的部分会被丢弃（保留最新的 MAX_SAMPLES 个点）。
 */
#define MAX_SAMPLES  500

// ═══════════════════════════════════════════════════
//  PWM / 振动强度参数
// ═══════════════════════════════════════════════════

/**
 * LEDC_CHANNEL：ESP32 LEDC PWM 通道号（仅 Core 2.x 需要）
 * Core 3.x 已不再需要手动指定通道，ledcAttach() 会自动分配。
 * 保留此行兼容旧版本，但代码中已不使用。
 */
// #define LEDC_CHANNEL  0  // Core 3.x 无需此项

/**
 * LEDC_FREQ_HZ：PWM 频率
 * 5000Hz（5kHz）对马达和 LED 都适合：
 *   - 马达：5kHz 以上人耳听不到线圈噪声
 *   - LED：5kHz 以上完全无闪烁感
 */
#define LEDC_FREQ_HZ     5000

/**
 * LEDC_RESOLUTION：PWM 精度（位数）
 * 8 位 = 值范围 0~255，粒度足够。
 * 注意：频率越高，可用精度越低；5kHz + 8bit 在 ESP32 上没问题。
 */
#define LEDC_RESOLUTION  8

/**
 * PWM_MIN / PWM_MAX：压力映射的 PWM 输出范围（0~255）
 *
 * ── 当前（LED 测试）──────────────────────────────
 *   PWM_MIN = 0   → 轻触时 LED 接近全灭
 *   PWM_MAX = 255 → 重按时 LED 全亮
 *   LED 无死区，全范围都有效。
 *
 * ── 换成 1027 马达后（修改这两行）────────────────
 *   PWM_MIN = 60  → 轻触时马达刚好能启动（死区约 20~30%）
 *   PWM_MAX = 255 → 重按时全力震动
 *   原因：马达有启动死区，占空比太低转不起来，
 *         把最小值抬到死区以上，轻触就能感觉到震动。
 */
#define PWM_MIN   65   // 马达启动死区补偿：低于此值马达不转，从这里开始才有感觉
#define PWM_MAX   255

